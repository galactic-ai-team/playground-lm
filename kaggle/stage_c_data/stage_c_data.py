# stage_c_data.py
# Kaggle CPU script kernel: Stage C data preparation, ONE session.
#
# This file is pushed as N separate kernels, one per session:
#   galacticaiteam/plm-stage-c-data-prep-s0
#   galacticaiteam/plm-stage-c-data-prep-s1
#   ...
#   galacticaiteam/plm-stage-c-data-prep-s7
#
# Each session kernel has its own SESSION constant below. The only difference
# between the N kernels is that number and the kernel id in kernel-metadata.json.
#
# Per session:
#   1. Restores its own previous run's output (self-reference in
#      kernel_sources via kernel-metadata-resume.json) — self-resume across
#      Kaggle's 12h CPU kill.
#   2. Calls prepare_fineweb.py ONCE with an explicit list of parquet paths
#      for its slice (no globs — globs would duplicate data across sessions).
#   3. Runs data/tokenize_shards.py to pack the session's JSONL into
#      train.bin/val.bin, forcing a re-run if new docs arrived after the
#      last tokenize.
#
# Session 0 also produces val.bin (5M token cap). Others pass --val-max-tokens 0.
#
# Output layout (each session kernel writes ONLY its own subdir):
#   /kaggle/working/stage-c/session-<N>/final/train.bin
#   /kaggle/working/stage-c/session-<N>/final/val.bin         (session 0 only)
#
# Stage C training mounts ALL N session kernels via kernel_sources and reads
# from /kaggle/input/plm-stage-c-data-prep-s<N>/stage-c/session-<N>/final/.
#
# Free-tools only.

import glob
import json
import os
import subprocess
import sys
from pathlib import Path

# ==== SESSION CONSTANT — EDIT PER PUSH ====
# This is the only line that differs between the N per-session kernels.
SESSION = 0
# ==========================================

N_SESSIONS = 8
if not 0 <= SESSION < N_SESSIONS:
    raise ValueError(f"SESSION={SESSION} out of range [0, {N_SESSIONS})")

# --- Paths ----------------------------------------------------------------

WORKING = Path("/kaggle/working")
INPUT = Path("/kaggle/input")
REPO_DIR = WORKING / "playground-lm"
OUT_ROOT = WORKING / "stage-c"
SESSION_DIR = OUT_ROOT / f"session-{SESSION}"
PREV_OUTPUT = INPUT / f"plm-stage-c-data-prep-s{SESSION}"   # own previous version

GIT_REPO = "https://github.com/galactic-ai-team/playground-lm.git"
GIT_BRANCH = "main"

# --- Budget ---------------------------------------------------------------
# Stage C target is 2.5B tokens per PRETRAIN_PLAN.md. FineWeb-Edu averages
# ~1000 tokens/doc, so 2.5B tokens / 8 sessions ≈ 312M tokens/session ≈
# 312,000 docs/session. Bump for safety in case avg doc is smaller.
DOCS_PER_SESSION = 350_000
VAL_MAX_TOKENS = 5_000_000 if SESSION == 0 else 0

# Shard-start offset. Each session starts at a distinct filename index so
# that even if the group ever concatenates JSONL files at the OS level, the
# names don't collide.
SHARD_START = SESSION * 1000

# --- FineWeb-Edu paths ----------------------------------------------------
# prepare_fineweb.py streams from HF. --data-files takes explicit parquet
# paths (not a glob), relative to the FineWeb-Edu sample root. The 14 files
# are named 000_00000.parquet ... 013_00000.parquet.
FINEWEB_SAMPLE_DIR = "sample/10BT"
FINEWEB_FILE_COUNT = 14
FINEWEB_FILE_PATTERN = "{index:03d}_00000.parquet"

# --- Helpers --------------------------------------------------------------

def log(msg: str) -> None:
    print(f"[stage-c/s{SESSION}] {msg}", flush=True)


def session_data_files() -> list[str]:
    """Return the explicit parquet paths for this session.

    Partition the 14 files across 8 sessions round-robin so each session
    gets 1-2 files. Round-robin (not contiguous) so if file sizes vary,
    sessions get roughly balanced loads.
    """
    all_indices = list(range(FINEWEB_FILE_COUNT))
    mine = all_indices[SESSION::N_SESSIONS]
    if not mine:
        raise RuntimeError(
            f"session {SESSION} got no files from {FINEWEB_FILE_COUNT} total"
        )
    paths = [f"{FINEWEB_SAMPLE_DIR}/{FINEWEB_FILE_PATTERN.format(index=i)}" for i in mine]
    log(f"data files: {len(paths)} of {FINEWEB_FILE_COUNT} → {paths}")
    return paths


def restore_own_previous_output() -> bool:
    """Copy the previous version of THIS kernel's output into WORKING.

    Since each session has its own kernel (plm-stage-c-data-prep-s<N>), the
    self-reference in kernel_sources mounts only this session's prior run.
    """
    if not PREV_OUTPUT.exists():
        log(f"no previous output at {PREV_OUTPUT}; starting fresh")
        return False

    prev_session_dir = PREV_OUTPUT / "stage-c" / f"session-{SESSION}"
    if not prev_session_dir.exists():
        log(f"previous output exists but no stage-c/session-{SESSION}/; starting fresh")
        return False

    log(f"restoring from {prev_session_dir}")
    # We restore only proc/ (JSONL docs). final/ is regenerated by tokenize.
    # Restoring final/ would risk stale train.bin shadowing a fresh one.
    prev_proc = prev_session_dir / "proc"
    if not prev_proc.exists():
        log("previous output has no proc/; starting fresh")
        return False

    proc_dir = SESSION_DIR / "proc"
    if proc_dir.exists():
        import shutil
        shutil.rmtree(proc_dir)
    proc_dir.parent.mkdir(parents=True, exist_ok=True)
    import shutil
    shutil.copytree(prev_proc, proc_dir)
    n_jsonl = sum(1 for _ in proc_dir.glob("fineweb-train-*.jsonl"))
    log(f"restored {n_jsonl} train JSONL shard(s)")
    return True


def clone_repo() -> None:
    if REPO_DIR.exists():
        log(f"{REPO_DIR} exists; pulling")
        subprocess.run(["git", "-C", str(REPO_DIR), "pull", "--ff-only"], check=True)
        return
    log(f"cloning {GIT_REPO} ({GIT_BRANCH})")
    subprocess.run(
        ["git", "clone", "--depth", "1", "--branch", GIT_BRANCH, GIT_REPO, str(REPO_DIR)],
        check=True,
    )


def pip_install() -> None:
    """Install runtime deps for prepare_fineweb.py and tokenize_shards.py.
    These aren't preinstalled on Kaggle CPU images."""
    pkgs = ["datasets", "tiktoken", "pyarrow"]
    log(f"pip install {' '.join(pkgs)}")
    result = subprocess.run(
        [sys.executable, "-m", "pip", "install", "--quiet", *pkgs],
    )
    if result.returncode != 0:
        raise RuntimeError("pip install failed; check internet or package names")


def find_script(name: str) -> Path:
    candidates = list(REPO_DIR.rglob(name))
    if not candidates:
        raise FileNotFoundError(f"{name} not found under {REPO_DIR}")
    for c in candidates:
        if "data" in c.parts:
            return c
    return candidates[0]


def count_jsonl_docs(proc_dir: Path) -> int:
    total = 0
    for f in proc_dir.glob("fineweb-train-*.jsonl"):
        with open(f, "rb") as fh:
            for _ in fh:
                total += 1
    return total


def newest_jsonl_mtime(proc_dir: Path) -> float:
    mtimes = [f.stat().st_mtime for f in proc_dir.glob("fineweb-*.jsonl")]
    return max(mtimes) if mtimes else 0.0


# --- Main -----------------------------------------------------------------

def main() -> int:
    log(f"session {SESSION}/{N_SESSIONS}, budget {DOCS_PER_SESSION:,} docs")
    log(f"output dir: {SESSION_DIR}")

    SESSION_DIR.mkdir(parents=True, exist_ok=True)

    # 1. Restore own previous run (self-resume across 12h kills).
    restore_own_previous_output()

    # 2. Clone repo, install deps.
    clone_repo()
    prepare_script = find_script("prepare_fineweb.py")
    tokenize_script = find_script("tokenize_shards.py")
    log(f"prepare: {prepare_script}")
    log(f"tokenize: {tokenize_script}")
    pip_install()

    # 3. Data files for this session.
    data_files = session_data_files()

    # 4. Proc dir.
    proc_dir = SESSION_DIR / "proc"
    proc_dir.mkdir(exist_ok=True)

    # 5. How many docs left to produce?
    already = count_jsonl_docs(proc_dir)
    remaining = max(0, DOCS_PER_SESSION - already)
    log(f"already written: {already:,} docs; need {remaining:,}")

    # 6. Prepare step (only if not already done).
    if remaining > 0:
        cmd = [
            sys.executable, str(prepare_script),
            "--data-files", *data_files,
            "--out", str(proc_dir),
            "--shard-start", str(SHARD_START),
            "--max-docs", str(remaining),
            "--val-max-tokens", str(VAL_MAX_TOKENS),
        ]
        log(f"$ {' '.join(cmd)}")
        result = subprocess.run(cmd, cwd=str(REPO_DIR))
        if result.returncode != 0:
            log(f"FATAL: prepare_fineweb.py exited {result.returncode}")
            return result.returncode
    else:
        log("prepare already complete; skipping")

    # 7. Tokenize step. Force a re-run if the newest JSONL is newer than the
    #    existing train.bin, so restored tokenize state doesn't shadow new
    #    docs. tokenize_shards.py uses .part files and is safe to rerun.
    final = SESSION_DIR / "final"
    final.mkdir(exist_ok=True)
    train_bin = final / "train.bin"
    newest_doc_mtime = newest_jsonl_mtime(proc_dir)
    train_bin_mtime = train_bin.stat().st_mtime if train_bin.exists() else 0.0
    stale = newest_doc_mtime > train_bin_mtime

    if stale or not train_bin.exists():
        log(f"tokenize needed (newest doc {newest_doc_mtime:.0f} > bin {train_bin_mtime:.0f})")
        cmd = [
            sys.executable, str(tokenize_script),
            "--input", str(proc_dir),
            "--out", str(final),
            "--force",
        ]
        log(f"$ {' '.join(cmd)}")
        result = subprocess.run(cmd, cwd=str(REPO_DIR))
        if result.returncode != 0:
            # --force may not be a supported flag on this script. Retry without.
            log(f"tokenize with --force exited {result.returncode}; retrying without --force")
            cmd = cmd[:-1]
            result = subprocess.run(cmd, cwd=str(REPO_DIR))
            if result.returncode != 0:
                log(f"FATAL: tokenize_shards.py exited {result.returncode}")
                return result.returncode
    else:
        log("tokenize already current; skipping")

    # 8. Report.
    if train_bin.exists():
        n_tok = train_bin.stat().st_size // 2
        log(f"train.bin: {n_tok:,} tokens")
    else:
        log("WARN: no train.bin produced")
    val_bin = final / "val.bin"
    if val_bin.exists():
        n_val = val_bin.stat().st_size // 2
        log(f"val.bin: {n_val:,} tokens")

    log("done")
    return 0


if __name__ == "__main__":
    sys.exit(main())